/**
 * Landing page library.
 *
 * Each entry powers a real, indexable, conversion-focused route at
 * /learn/:slug rendered by src/pages/LandingPage.tsx. Content is
 * data-driven so the library stays consistent, fast and easy to extend.
 */

export type LandingCategory =
  | "Frontend"
  | "Backend"
  | "Full Stack"
  | "AI & Data"
  | "Mobile"
  | "Career"
  | "No-Code & Tools";

export interface LandingSpec {
  slug: string;
  /** Primary keyword / topic used in the H1 and title. */
  topic: string;
  category: LandingCategory;
  /** Conversion hook shown under the H1. */
  hook: string;
  /** Who the page speaks to. */
  audience: string;
  /** 4 syllabus modules. */
  modules: [string, string, string, string];
  /** 3 concrete outcomes. */
  outcomes: [string, string, string];
  /** Extra long-tail keywords. */
  keywords: string;
  /** Program length in weeks: 5 (₹699) or 10 (₹2,999). */
  weeks: 5 | 10;
}

export interface LandingPageContent extends LandingSpec {
  path: string;
  title: string;
  description: string;
  h1: string;
  price: number;
  duration: string;
  faqs: { question: string; answer: string }[];
}

